import BotLinkerStrategy from "../../interfaces/BotLinkerStrategyInterface";
import IBotModel, {
  IProcessTree,
  IProcessTreeNodeInfo,
  IProcessTreeStructure,
} from "../../interfaces/BotModelInterface";
import {
  comment,
  padActionFor,
  padContainerFor,
  padScopeFor,
  PadStep,
  todo,
} from "./padMapping";

type TreeItem = string | IProcessTreeStructure;

const INDENT = "    ";
const GATEWAYS = new Set(["BinaryDecision", "CaseDecision", "MultipleDecision", "ParallelSplit"]);
const LOOPS = new Set(["ForEachLoop", "ConditionalLoop"]);

/**
 * Translates a process tree into a Power Automate Desktop skeleton flow in Robin, PAD's text
 * format for copying and pasting actions. Mapped operations become PAD actions with TODO
 * parameters where values or UI elements are missing; anything without a PAD action becomes a
 * TODO comment. Unlike the Robot Framework and taskt linkers, it never throws on unknown nodes.
 */
class PowerAutomateDesktopLinker implements BotLinkerStrategy {
  botModel?: IBotModel;

  linkBot(botModel: IBotModel): string {
    this.botModel = botModel;
    const processTree: IProcessTree =
      typeof botModel.processTree === "string"
        ? JSON.parse(botModel.processTree)
        : botModel.processTree;
    return generatePadFlow(botModel.name, processTree);
  }
}

export function generatePadFlow(name: string, processTree: IProcessTree): string {
  const writer = new PadWriter(processTree.nodeInfo || {});
  const body = writer.write(processTree.tree, 0);
  const header = [
    comment(`Power Automate Desktop skeleton for "${name}", generated by OntoRPA`),
    comment("Paste into an empty subflow. Lines marked TODO need attention before the flow runs."),
  ];
  if (writer.placeholders.length > 0) {
    header.push(comment("Placeholders for conditions and collections: replace them with real values"));
    header.push(...writer.placeholders);
  }
  return [...header, "", ...body].join("\n") + "\n";
}

class PadWriter {
  placeholders: string[] = [];
  private counters: Record<string, number> = {};

  constructor(private nodeInfo: Record<string, IProcessTreeNodeInfo>) {}

  write(item: TreeItem, depth: number): string[] {
    if (typeof item === "string") {
      return this.leaf(item).map((line) => INDENT.repeat(depth) + line);
    }
    return Object.entries(item).flatMap(([key, children]) => this.block(key, children, depth));
  }

  private writeAll(items: TreeItem[], depth: number): string[] {
    return items.flatMap((item) => this.write(item, depth));
  }

  private leaf(nodeId: string): string[] {
    const info = this.nodeInfo[nodeId];
    if (!info) {
      return [comment(`TODO: unknown step ${nodeId}`)];
    }
    return padStepLines(info);
  }

  private block(key: string, children: TreeItem[], depth: number): string[] {
    if (key === "Flow" || key === "Process") {
      return this.writeAll(children, depth);
    }
    const info = this.nodeInfo[key];
    const concept = info?.concept || "";
    const indent = INDENT.repeat(depth);

    if (key.includes("Gateway") || GATEWAYS.has(concept)) {
      return this.gateway(info, concept, children, depth);
    }
    if (key.startsWith("Loop") || LOOPS.has(concept)) {
      return this.loop(info, concept, children, depth);
    }

    const step: PadStep = { label: info?.label || key, source: info?.source };
    const wrapper = padContainerFor(concept) || padScopeFor(info?.source?.context);
    if (wrapper) {
      return [
        ...wrapper.setup(step).map((line) => indent + line),
        ...this.writeAll(children, depth),
        ...wrapper.cleanup(step).map((line) => indent + line),
      ];
    }

    // Scopes without a PAD equivalent (desktop apps, SAP, custom scopes): keep the body
    const context = info?.source?.context;
    const hint =
      info?.mappingStatus === "manual" || info?.mappingStatus === "unmapped"
        ? unmappedComment(info)
        : todo(
            step,
            context
              ? `attach to the ${context} application; UI actions need the UI element picker`
              : "scope without a Power Automate Desktop equivalent"
          );
    return [indent + hint, ...this.writeAll(children, depth)];
  }

  private gateway(
    info: IProcessTreeNodeInfo | undefined,
    concept: string,
    branches: TreeItem[],
    depth: number
  ): string[] {
    const indent = INDENT.repeat(depth);
    const step: PadStep = { label: info?.label || "Decision", source: info?.source };
    const expression = info?.source?.expression;
    const lines: string[] = [];

    if (concept === "ParallelSplit") {
      lines.push(indent + todo(step, "Power Automate Desktop has no parallel branches; they run one after another"));
      branches.forEach((branch, index) => {
        lines.push(indent + comment(`Branch ${index + 1}`));
        lines.push(...this.write(branch, depth));
      });
      return lines;
    }

    if (concept === "BinaryDecision" && branches.length === 2) {
      const condition = this.placeholder("Condition", (name) => `SET ${name} TO False`);
      lines.push(indent + todo(step, expression ? `translate the condition; UiPath uses ${expression}` : "set the condition"));
      lines.push(`${indent}IF ${condition} = True THEN`);
      lines.push(...this.write(branches[0], depth + 1));
      const elseLines = this.write(branches[1], depth + 1);
      if (elseLines.length > 0) {
        lines.push(`${indent}ELSE`);
        lines.push(...elseLines);
      }
      lines.push(`${indent}END`);
      return lines;
    }

    const value = this.placeholder("CaseValue", (name) => `SET ${name} TO 1`);
    lines.push(
      indent +
        todo(step, `set the case values${expression ? `; UiPath switches on ${expression}` : ""}`)
    );
    lines.push(`${indent}SWITCH ${value}`);
    branches.forEach((branch, index) => {
      lines.push(`${indent}${INDENT}CASE = ${index + 1}`);
      lines.push(...this.write(branch, depth + 2));
    });
    lines.push(`${indent}END`);
    return lines;
  }

  private loop(
    info: IProcessTreeNodeInfo | undefined,
    concept: string,
    body: TreeItem[],
    depth: number
  ): string[] {
    const indent = INDENT.repeat(depth);
    const step: PadStep = { label: info?.label || "Loop", source: info?.source };
    const expression = info?.source?.expression;
    const reason = info?.source?.reason;

    if (concept === "ConditionalLoop") {
      const condition = this.placeholder("Condition", (name) => `SET ${name} TO False`);
      return [
        indent + todo(step, expression ? `translate the loop condition; UiPath uses ${expression}` : "set the loop condition"),
        `${indent}LOOP WHILE (${condition}) = (True)`,
        ...this.writeAll(body, depth + 1),
        `${indent}END`,
      ];
    }

    const collection = this.placeholder("Collection", (name) => `Variables.CreateNewList List=> ${name}`);
    const hint = reason || (expression ? `set the list to loop over; UiPath loops over ${expression}` : "set the list to loop over");
    return [
      indent + todo(step, hint),
      `${indent}LOOP FOREACH CurrentItem IN ${collection}`,
      ...this.writeAll(body, depth + 1),
      `${indent}END`,
    ];
  }

  /** Declares a numbered placeholder variable, e.g. Condition1, and returns its name. */
  private placeholder(kind: string, declaration: (name: string) => string): string {
    this.counters[kind] = (this.counters[kind] || 0) + 1;
    const name = `${kind}${this.counters[kind]}`;
    this.placeholders.push(declaration(name));
    return name;
  }
}

/**
 * The PAD lines of a single step (not a gateway, loop or container): its action, or a TODO
 * comment if there is none. Also used to preview a step in the modeler.
 */
export function padStepLines(info: IProcessTreeNodeInfo): string[] {
  const step: PadStep = { label: info.label, source: info.source };
  const status = info.mappingStatus || (info.concept ? "mapped" : "unmapped");
  if (status !== "mapped") {
    return [unmappedComment(info)];
  }
  const action = padActionFor(info.concept);
  return action
    ? action(step)
    : [todo(step, `no Power Automate Desktop action for ${info.concept} yet`)];
}

function unmappedComment(info: IProcessTreeNodeInfo): string {
  const source = info.source;
  const origin = source ? ` (UiPath ${source.activityType}${source.context ? ` in ${source.context}` : ""})` : "";
  const reason =
    info.mappingStatus === "manual"
      ? source?.reason || "needs manual redesign"
      : "no ontology operation, rebuild by hand";
  return comment(`TODO "${info.label}"${origin}: ${reason}`);
}

export default PowerAutomateDesktopLinker;
